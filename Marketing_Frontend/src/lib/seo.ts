/**
 * One place that decides how a public marketing page describes itself.
 *
 * Three audiences read these pages and they want different things:
 *
 *  - **Search engines (SEO)** want a unique title and description per URL, a
 *    canonical link, a real heading hierarchy and internal links between
 *    related pages.
 *  - **Answer engines (AEO)** — featured snippets, voice assistants — want the
 *    question asked in the user's own words and answered immediately after, in
 *    a couple of sentences, backed by FAQPage structured data.
 *  - **Generative engines (GEO)** — assistants that summarise rather than link
 *    — want unambiguous entity names, concrete specifics and self-contained
 *    sentences that survive being quoted away from their page.
 *
 * All three are served by the same discipline: say one true, specific thing per
 * block, and mark it up so a machine can tell what it is. Nothing here invents
 * a claim the product cannot support.
 */

/**
 * Absolute origin for canonical and og:url. Absolute URLs are required —
 * a relative canonical is ignored, and a relative og:image will not render in
 * any social preview.
 *
 * Configurable so pointing a custom domain at this deployment is an
 * environment change. `public/sitemap.xml` is static and carries the same
 * origin, so it has to be updated alongside a domain move.
 */
export const SITE_URL = (
  import.meta.env["VITE_SITE_URL"] ?? "https://scaleezy-marketing-hub.vercel.app"
).replace(/\/+$/, "");

export const SITE_NAME = "Scaleezy Marketing Hub";

/** Default social card. Generated by scripts/build-og-images.mjs. */
export const DEFAULT_OG_IMAGE = "/og/og-default.png";

export function absoluteUrl(path: string): string {
  return `${SITE_URL}${path.startsWith("/") ? path : `/${path}`}`;
}

export interface MarketingPageSeo {
  /** The <title>. Unique per URL, front-loaded with the page's own subject. */
  title: string;
  /** The meta description. One sentence, 140-160 characters, no boilerplate. */
  description: string;
  /** Path only, e.g. "/how-it-works". Becomes canonical and og:url. */
  path: string;
  /** Path to the social card for this page. */
  image?: string;
  /**
   * Structured data for this page. Emitted as JSON-LD by <JsonLd>, not here —
   * TanStack's head() takes meta and links, and script children are simpler to
   * keep honest when they render with the page body.
   */
  keywords?: readonly string[];
}

/**
 * Builds the `head()` payload for a public page.
 *
 * og:type, twitter:card and twitter:site come from __root.tsx and are not
 * repeated; duplicate og tags are a common cause of a wrong social preview.
 */
export function marketingHead(seo: MarketingPageSeo) {
  const url = absoluteUrl(seo.path);
  const image = absoluteUrl(seo.image ?? DEFAULT_OG_IMAGE);

  return {
    meta: [
      { title: seo.title },
      { name: "description", content: seo.description },
      ...(seo.keywords?.length ? [{ name: "keywords", content: seo.keywords.join(", ") }] : []),
      { property: "og:title", content: seo.title },
      { property: "og:description", content: seo.description },
      { property: "og:url", content: url },
      { property: "og:image", content: image },
      { property: "og:site_name", content: SITE_NAME },
      { name: "twitter:title", content: seo.title },
      { name: "twitter:description", content: seo.description },
      { name: "twitter:image", content: image },
      // The marketing pages are the only ones that should be indexed; the app
      // itself is behind auth and /login already sets noindex.
      { name: "robots", content: "index, follow, max-image-preview:large" },
    ],
    links: [{ rel: "canonical", href: url }],
  };
}

