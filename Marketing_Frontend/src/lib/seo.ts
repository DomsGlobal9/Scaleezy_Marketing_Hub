/**
 * Who Scaleezy is. Emitted once, on the home page, so the entity is defined in
 * one place — repeating a slightly different Organization on every page is how
 * a knowledge panel ends up with conflicting facts.
 */
export function organizationSchema() {
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    "@id": `${SITE_URL}/#organization`,
    name: "Scaleezy",
    url: SITE_URL,
    logo: absoluteUrl("/brand/scaleezy-wordmark.webp"),
    description:
      "Scaleezy builds brand-aware marketing software that generates, reviews and publishes social content under human approval.",
  };
}

export function softwareApplicationSchema() {
  return {
    "@context": "https://schema.org",
    "@type": "SoftwareApplication",
    "@id": `${SITE_URL}/#software`,
    name: SITE_NAME,
    applicationCategory: "BusinessApplication",
    applicationSubCategory: "Social Media Marketing Software",
    operatingSystem: "Web browser",
    url: SITE_URL,
    publisher: { "@id": `${SITE_URL}/#organization` },
    description:
      "An AI social media marketing platform that learns a brand from its own documents and references, drafts posters, carousels, video and copy through the AI providers each workspace configures, and publishes to Instagram, Facebook, LinkedIn, X and YouTube only after a person approves the work.",
    featureList: [
      "Brand knowledge base built from documents, transcripts and reference posts",
      "Per-capability AI provider routing with failover",
      "Human approval gate before any post is published",
      "Multi-channel publishing to Instagram, Facebook, LinkedIn, X and YouTube",
      "Shared engagement inbox with AI-drafted replies",
      "Performance, lead and revenue attribution per post",
      "Workspace-level tenant isolation and audit trails",
    ],
  };
}

export interface FaqEntry {
  question: string;
  answer: string;
}

/**
 * FAQPage markup. The answers must be the same text a reader sees on the page —
 * structured data that does not match the visible content is a manual-action
 * risk, and an answer engine that quotes a hidden answer misrepresents you.
 */
export function faqSchema(entries: readonly FaqEntry[], pagePath: string) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    "@id": `${absoluteUrl(pagePath)}#faq`,
    mainEntity: entries.map((entry) => ({
      "@type": "Question",
      name: entry.question,
      acceptedAnswer: { "@type": "Answer", text: entry.answer },
    })),
  };
}

export function breadcrumbSchema(trail: readonly { name: string; path: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: trail.map((crumb, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: crumb.name,
      item: absoluteUrl(crumb.path),
    })),
  };
}

export function webPageSchema(seo: MarketingPageSeo) {
  return {
    "@context": "https://schema.org",
    "@type": "WebPage",
    "@id": `${absoluteUrl(seo.path)}#webpage`,
    url: absoluteUrl(seo.path),
    name: seo.title,
    description: seo.description,
    isPartOf: { "@id": `${SITE_URL}/#organization` },
  };
}
